logger = logging.getLogger(__name__)


def category_slug(name: str) -> str:
    """Normalize a category or group name to its persistent lowercase id.

    Config-backed backends (e.g. SimpleFIN) regenerate ids from names with
    this algorithm each session while transactions retain previously assigned
    ids, so its output must never change — including the ASCII-only stripping
    of non-ASCII characters ("Café" → "caf"). Use category_equivalence_key
    for comparing names, and stable_category_id for CSV import ids.
    """
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def category_equivalence_key(name: str) -> str:
    """Normalize a category name for equivalence comparison.

    Unicode-aware, unlike category_slug: distinct non-Latin names produce
    distinct keys instead of all collapsing to the empty string. This is the
    single normalization used by duplicate-category detection across CSV
    import, configuration, and TUI creation.
    """
    key = re.sub(r"\W+", "_", name.lower())
    return re.sub(r"_+", "_", key).strip("_")


def stable_category_id(name: str) -> str:
    """Return the canonical id for categories generated by CSV import.

    CSV-imported ids are new in this backend (no legacy databases exist), so
    they use the Unicode-aware key with a ``cat_`` prefix. Equivalence with
    ids from other surfaces must be checked by comparing
    ``category_equivalence_key`` of the names, not the ids.
    """
    key = category_equivalence_key(name)
    return f"cat_{key}" if key else "cat_uncategorized"


